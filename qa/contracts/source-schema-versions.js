export const sourceSchemaVersions = Object.freeze(
  Object.fromEntries(Object.entries(rawVersions).map(([key,fields]) => [key,Object.freeze(fields)]))
);
export function validateSourceSchema(version, header) {
  const expected = sourceSchemaVersions[version];
  if (!expected) return Object.freeze({ok:false,code:'UNKNOWN_SOURCE_VERSION'});
  if (!Array.isArray(header) || header.length !== expected.length || header.some(v=>typeof v!=='string'))
    return Object.freeze({ok:false,code:'HEADER_SHAPE_MISMATCH'});
  const mismatch = header.findIndex((v,i)=>v!==expected[i]);
  if (mismatch >= 0) return Object.freeze({ok:false,code:'HEADER_FIELD_MISMATCH',column:mismatch+1});
  return Object.freeze({ok:true,code:'VERIFIED_EXACT_HEADER'});
}
export function mapSourceRow(version, header, row) {
  const schema=validateSourceSchema(version,header);
  if(!schema.ok) return Object.freeze({status:'REVIEW',reason:schema.code});
  if (!Array.isArray(row) || row.length!==header.length || row.some(v=>v!==null && v!==undefined && !['string','number','boolean'].includes(typeof v)))
    return Object.freeze({status:'REVIEW',reason:'ROW_SHAPE_MISMATCH'});
  // Metadata only. Normalization and projection require an explicit per-version,
  // per-field approved adapter. This function intentionally never returns raw values.
  return Object.freeze({status:'VALIDATED_SOURCE_SHAPE',sourceVersion:version,columns:header.length});
}
